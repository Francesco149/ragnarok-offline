#!/usr/bin/env python3
"""What a guild castle's treasure boxes hold: Ragu Memo's jRO table of February 2004.

Ragu Memo (ragmemo.s33.xrea.com/gvg_box.html, Wayback capture 20040206224529;
research/notes/round18-review.md) lists the items a castle's treasure box gave
on jRO, each with its rate as players counted it: twelve every castle shares
(3 Carat Diamond 1/2.5, Yggdrasil Seed 1/6 ...) and four of each castle's own
(its god-item material at 1/250, then three rarer). tools/import/castle_treasure.tsv
is that page row by row, with mod0631's item ids (by the JName column) and the
rate on Athena's scale (per 10000).

Which boxes are a castle's: mod0631's forty TREASURE_BOXes (1324-1363) in pairs,
in region order (Al De Baran 1-5, Geffen 1-5, Payon 1-5, Prontera 1-5). The
even box of each pair drops that castle's god-item material in mod0631 (round 11:
all twenty agree with Arctic Breeze's castle list), and jAthena //0974
(2004-05-16, script/npc/gvg/test/tbox.txt) puts the pair in that castle's room.
mod0631's own drops for the boxes are an emulator's stand-in (eight slots, the
castles' other items a different set, the material at 1/1000): both boxes of a
pair get the castle's whole Ragu Memo list instead, common items and its own.
The page does not split them between two boxes, and players counted what came
out of a castle's boxes, not of one kind.

  python3 tools/import/castle_treasure.py REPO_ROOT
writes data/db/treasure.toml.
"""
import sys
from pathlib import Path

root = Path(sys.argv[1] if len(sys.argv) > 1 else '.')
rows = []
for line in (root / 'tools/import/castle_treasure.tsv').read_text(encoding='utf8').splitlines():
    if line.startswith('#') or not line.strip():
        continue
    castle, item, rate, name, note = (line.split('\t') + [''] * 5)[:5]
    rows.append((castle, int(item), int(rate), name))

ORDER = [f'{p}{i}' for p in ('aldeg_cas0', 'gefg_cas0', 'payg_cas0', 'prtg_cas0') for i in range(1, 6)]
common = [r for r in rows if r[0] == '*']
assert len(common) == 12, len(common)

out = [
    '# Generated by tools/import/castle_treasure.py: do not edit; change the script or',
    '# tools/import/castle_treasure.tsv and run it again.',
    '[meta]',
    'tier = "period"',
    'source = "Ragu Memo, ragmemo.s33.xrea.com/gvg_box.html (jRO), Wayback 20040206224529; '
    'boxes by castle: mod0631 db/mob_db.txt pairs, jAthena //0974 (2004-05-16) script/npc/gvg/test/tbox.txt"',
    'note = "replaces the drops of these monsters in mobs.toml; rate per 10000, as players counted 1/N on jRO"',
    '',
]
for k, castle in enumerate(ORDER):
    own = [r for r in rows if r[0] == castle]
    assert len(own) == 4, (castle, len(own))
    for box in (1324 + 2 * k, 1325 + 2 * k):
        out.append('[[box]]')
        out.append(f'mob = {box}')
        out.append(f'castle = "{castle}"')
        drops = ', '.join(f'{{ item = {i}, rate = {r} }}' for _, i, r, _ in common + own)
        out.append(f'drops = [{drops}]')
        out.append('')
(root / 'data/db/treasure.toml').write_text('\n'.join(out), encoding='utf8')
print(f'{len(ORDER) * 2} boxes, {len(common)} common items and 4 of each castle')
